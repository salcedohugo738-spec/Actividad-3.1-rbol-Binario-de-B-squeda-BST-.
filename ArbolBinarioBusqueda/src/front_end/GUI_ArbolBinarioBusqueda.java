    private void btn_CrearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_CrearActionPerformed
if (arbol != null && !arbol.estaVacio()) {
            int op = JOptionPane.showConfirmDialog(this,
                    "Ya existe un árbol con " + arbol.getTamanio() + " empleado(s).\n"
                    + "Si crea uno nuevo se perderán esos datos. ¿Desea continuar?",
                    "Crear árbol", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
            if (op != JOptionPane.YES_OPTION) {
                mostrar("Crear árbol", "Operación cancelada. Se conserva el árbol actual.");
                return;
            }
        }
        arbol = new ArbolBST();
        panelArbol.setArbol(arbol);
        limpiarCampos();
        mostrar("Crear árbol", "El árbol está listo para utilizarse.\n"
                + "Capture los datos del empleado y presione \"Agregar Empleado\".");
    }//GEN-LAST:event_btn_CrearActionPerformed

    private void btn_buscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_buscarActionPerformed
    final String op = "Buscar empleado";
        if (!hayArbol(op)) {
            return;
        }
        try {
            Integer id = Validaciones.parseId(txt_ID.getText());
            Empleado e = arbol.buscar(id);
            if (e == null) {
                panelArbol.setIdResaltado(null);
                mostrar(op, "NO ENCONTRADO: no existe un empleado con el ID " + id + "."
                        + (arbol.estaVacio() ? "\n(El árbol está vacío.)" : ""));
            } else {
                panelArbol.setIdResaltado(id);
                mostrar(op, "Empleado encontrado:\n" + detalle(e));
            }
        } catch (IllegalArgumentException ex) {
            error(op, ex.getMessage());
        }
    }//GEN-LAST:event_btn_buscarActionPerformed

