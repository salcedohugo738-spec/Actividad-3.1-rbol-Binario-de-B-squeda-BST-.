    /** Pregunta qué recorrido mostrar y lo ejecuta. */
    private void elegirRecorrido() {
        if (!hayArbol("Mostrar recorridos")) {
            return;
        }
        String[] opciones = {"Inorden", "Preorden", "Postorden", "Los tres"};
        int r = JOptionPane.showOptionDialog(this, "¿Qué recorrido desea mostrar?", "Mostrar recorridos",
                JOptionPane.DEFAULT_OPTION, JOptionPane.QUESTION_MESSAGE, null, opciones, opciones[0]);
        switch (r) {
            case 0 -> mostrarInOrden();
            case 1 -> mostrarPreOrden();
            case 2 -> mostrarPostOrden();
            case 3 -> mostrar("Recorridos (inorden, preorden y postorden)",
                    cuerpoInOrden() + "\n\n" + cuerpoPreOrden() + "\n\n" + cuerpoPostOrden());
            default -> { /* ventana cerrada: no hacer nada */ }
        }
    }

    private void mostrarInOrden() {
        mostrar("Recorrido inorden", cuerpoInOrden());
    }

    private void mostrarPreOrden() {
        mostrar("Recorrido preorden", cuerpoPreOrden());
    }

    private void mostrarPostOrden() {
        mostrar("Recorrido postorden", cuerpoPostOrden());
    }

    private String cuerpoInOrden() {
        return listaEmpleados("INORDEN (izquierdo, raíz, derecho) - ID ascendente", arbol.mostrarInOrden());
    }

    private String cuerpoPreOrden() {
        return listaEmpleados("PREORDEN (raíz, izquierdo, derecho)", arbol.mostrarPreOrden());
    }

    private String cuerpoPostOrden() {
        return listaEmpleados("POSTORDEN (izquierdo, derecho, raíz)", arbol.mostrarPostOrden());
    }

    /** Pregunta qué cálculo mostrar (amplitud, profundidad o ambos). */
    private void elegirCalculo() {
        if (!hayArbol("Calcular amplitud y profundidad")) {
            return;
        }
        String[] opciones = {"Amplitud", "Profundidad", "Ambas"};
        int r = JOptionPane.showOptionDialog(this, "¿Qué desea calcular?", "Amplitud y profundidad",
                JOptionPane.DEFAULT_OPTION, JOptionPane.QUESTION_MESSAGE, null, opciones, opciones[2]);
        switch (r) {
            case 0 -> calcularAmplitud();
            case 1 -> calcularProfundidad();
            case 2 -> mostrar("Amplitud y profundidad", cuerpoAmplitud() + "\n\n" + cuerpoProfundidad());
            default -> { /* ventana cerrada: no hacer nada */ }
        }
    }

    private void calcularAmplitud() {
        mostrar("Calcular amplitud", cuerpoAmplitud());
    }

    private void calcularProfundidad() {
        mostrar("Calcular profundidad", cuerpoProfundidad());
    }

    private String cuerpoAmplitud() {
        int a = arbol.amplitud();
        return "Amplitud máxima: " + a + " nodo(s) en un mismo nivel."
                + "\n(Es el nivel más ancho, no el total de empleados; el total es " + arbol.getTamanio() + ".)";
    }

    private String cuerpoProfundidad() {
        int p = arbol.profundidad();
        return "Profundidad máxima: " + p + " nivel(es)."
                + "\n(Se mide en niveles: árbol vacío = 0, un solo nodo = 1.)";
    }

   

  
