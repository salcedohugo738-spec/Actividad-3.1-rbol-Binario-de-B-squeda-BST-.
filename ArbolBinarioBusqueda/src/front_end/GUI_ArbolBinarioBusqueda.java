    private void btn_DestruirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_DestruirActionPerformed
    final String op = "Destruir árbol";
        if (!hayArbol(op)) {
            return;
        }
        if (!arbol.estaVacio()) {
            int r = JOptionPane.showConfirmDialog(this,
                    "Se eliminarán los " + arbol.getTamanio() + " empleado(s) del árbol. ¿Desea continuar?",
                    op, JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
            if (r != JOptionPane.YES_OPTION) {
                mostrar(op, "Operación cancelada. El árbol no se modificó.");
                return;
            }
        }
        arbol.destruirArbol();
        panelArbol.actualizar();
        limpiarCampos();
        mostrar(op, "El árbol quedó vacío (0 empleados) y está listo para utilizarse nuevamente.");
    }//GEN-LAST:event_btn_DestruirActionPerformed

