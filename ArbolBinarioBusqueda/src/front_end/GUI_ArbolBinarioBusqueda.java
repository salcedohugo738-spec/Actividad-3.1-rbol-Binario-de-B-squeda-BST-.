    private static String dinero(Double d) {
        return String.format(Locale.US, "$%,.2f", d);
    }

    private static String detalle(Empleado e) {
        return "ID:           " + e.getId()
                + "\nNombre:       " + e.getNombre()
                + "\nPuesto:       " + e.getPuesto()
                + "\nDepartamento: " + e.getDepartamento()
                + "\nSalario:      " + dinero(e.getSalario());
    }

    private static String listaEmpleados(String titulo, List<Empleado> lista) {
        StringBuilder sb = new StringBuilder(titulo).append('\n');
        if (lista.isEmpty()) {
            return sb.append("(El árbol está vacío; no hay empleados que mostrar.)").toString();
        }
        int n = 1;
        for (Empleado e : lista) {
            sb.append(String.format("%2d) ID %d | %s | %s | %s | %s%n", n++, e.getId(), e.getNombre(),
                    e.getPuesto(), e.getDepartamento(), dinero(e.getSalario())));
        }
        return sb.toString().stripTrailing();
    }

    /** Dibuja el árbol como texto (raíz arriba, ramas con sangría). */
    private static void estructura(NodoBST n, String prefijo, String rama, StringBuilder sb) {
        if (n == null) {
            return;
        }
        sb.append(prefijo).append(rama).append(n.getDato().getId())
                .append(" (").append(n.getDato().getNombre()).append(")\n");
        String hijoPrefijo = prefijo + (rama.isEmpty() ? "" : (rama.startsWith("├") ? "│   " : "    "));
        boolean hayDer = n.getDerecho() != null;
        estructura(n.getIzquierdo(), hijoPrefijo, hayDer ? "├─I: " : "└─I: ", sb);
        estructura(n.getDerecho(), hijoPrefijo, "└─D: ", sb);
    }

