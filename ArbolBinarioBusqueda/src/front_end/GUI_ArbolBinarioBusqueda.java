    /** Verifica que el árbol exista; si no, avisa al usuario. */
    private boolean hayArbol(String operacion) {
        if (arbol == null) {
            error(operacion, "Primero debe crear el árbol con el botón \"Crear Arbol\".");
            return false;
        }
        return true;
    }

    /** Reemplaza el contenido del área de resultados indicando la operación realizada. */
    private void mostrar(String operacion, String texto) {
        txa_Resultados.setText("=== " + operacion.toUpperCase() + " ===\n" + texto);
        txa_Resultados.setCaretPosition(0);
    }

    /** Muestra un error tanto en el área de resultados como en una ventana. */
    private void error(String operacion, String mensaje) {
        mostrar(operacion, "ERROR: " + mensaje);
        JOptionPane.showMessageDialog(this, mensaje, operacion, JOptionPane.WARNING_MESSAGE);
    }

